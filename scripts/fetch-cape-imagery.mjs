import { writeFile } from 'node:fs/promises';

// Cache imagery at build-authoring time: gameplay never depends on a map service.
// Export extents can differ from the requested bbox; retain the returned bounds
// so every level remains geographically registered on the spherical Earth.
const latitude = 28.561857, longitude = -80.577366;
const endpoint = 'https://basemap.nationalmap.gov/arcgis/rest/services/USGSImageryOnly/MapServer/export';
const layers = [];
for (const [name, spanM, size] of [['local', 4400, 2048], ['mid', 36000, 4096], ['wide', 360000, 4096]]) {
  const halfLat = spanM / 2 / 111195;
  const halfLon = halfLat / Math.cos(latitude * Math.PI / 180);
  const url = new URL(endpoint);
  Object.entries({ bbox: [longitude - halfLon, latitude - halfLat, longitude + halfLon, latitude + halfLat].join(','),
    bboxSR: '4326', imageSR: '4326', size: `${size},${size}`, format: 'png32', transparent: 'true', f: 'json' })
    .forEach(([key, value]) => url.searchParams.set(key, value));
  const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
  if (!response.ok) throw new Error(`USGS export failed: ${response.status}`);
  const data = await response.json();
  if (!data.href || !data.extent) throw new Error(JSON.stringify(data));
  const image = await fetch(data.href, { signal: AbortSignal.timeout(120000) });
  if (!image.ok) throw new Error(`USGS image failed: ${image.status}`);
  const bytes = Buffer.from(await image.arrayBuffer());
  if (bytes.readUInt32BE(0) !== 0x89504e47) throw new Error('Export did not return PNG');
  const file = `cape_albedo_${name}.png`;
  await writeFile(new URL(`../public/assets/textures/${file}`, import.meta.url), bytes);
  const { xmin, ymin, xmax, ymax } = data.extent;
  layers.push({ name, file, bounds: [xmin, ymin, xmax, ymax], width: data.width, height: data.height });
  console.log(`${name}: ${data.width} x ${data.height}, ${bytes.length} bytes`);
}
await writeFile(new URL('../src/config/capeImagery.ts', import.meta.url),
  '// Generated by scripts/fetch-cape-imagery.mjs from USGS The National Map.\n' +
  `export const CAPE_IMAGERY_LAYERS = ${JSON.stringify(layers, null, 2)} as const;\n`);
